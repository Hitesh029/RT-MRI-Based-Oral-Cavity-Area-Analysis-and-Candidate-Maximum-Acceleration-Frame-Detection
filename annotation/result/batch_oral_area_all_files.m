%% batch_oral_area_all_files.m
% Batch runner for many annotated MRI MAT files.
%
% PURPOSE
%   1. Find all usable MAT datasets in one folder.
%   2. Run the EXISTING oral-area detection pipeline frame-by-frame.
%   3. Save per-dataset calculations.
%   4. Save Oral Area vs Frame graph automatically (.png + .fig).
%   5. Save CSV and MAT results.
%   6. Create one master summary CSV for all datasets.
%
% IMPORTANT
%   This file DOES NOT change the established C1/C2 detection methodology.
%   It calls your existing functions:
%       loadData
%       preprocessData
%       identifyC1
%       identifyC2
%       findC1Start
%       findC2Start
%       findC1End
%       findC2End
%
% REQUIRED
%   Keep this file in the same MATLAB project folder as those functions.
%
% FILE PAIR SUPPORT
%   If final file M1_400.mat contains annotations and M1_400_temp.mat
%   contains imgs, use the updated loadData.m that combines them.
%
% NOTE
%   Velocity/acceleration are intentionally NOT calculated here because
%   actual MRI temporal resolution dt/fps has not yet been confirmed.

clear;
clc;
close all;

%% ================= USER SETTINGS =================
dataFolder = pwd;                       % folder containing MAT datasets
outputRoot = fullfile(dataFolder, 'BATCH_ORAL_AREA_RESULTS');

% Same geometry configuration used in your current pipeline
anchor = [700, 160];
tolerancePx = 3.0;

% false = batch runs without opening every frame figure
showFrameFigures = false;

% Save a diagnostic frame image only when a frame fails?
saveFailureFigures = false;

if ~exist(outputRoot, 'dir')
    mkdir(outputRoot);
end

fprintf('\n============================================================\n');
fprintf('       BATCH ORAL AREA PROCESSING\n');
fprintf('============================================================\n');
fprintf('Input folder : %s\n', dataFolder);
fprintf('Output folder: %s\n\n', outputRoot);

%% ================= DISCOVER MAT FILES =================
allFiles = dir(fullfile(dataFolder, '*.mat'));

if isempty(allFiles)
    error('No MAT files found in: %s', dataFolder);
end

% Build dataset list.
% Prefer final NAME.mat when both NAME.mat and NAME_temp.mat exist.
% If only NAME_temp.mat exists and it has populated annotations, use it.
datasetPaths = {};
datasetNames = {};

for i = 1:numel(allFiles)
    fname = allFiles(i).name;

    % Ignore result MAT files generated by this script/pipeline
    if contains(lower(fname), 'summary') || ...
       contains(lower(fname), 'result') || ...
       contains(lower(fname), 'area_calculation')
        continue;
    end

    fullPath = fullfile(allFiles(i).folder, fname);
    [~, base, ~] = fileparts(fname);

    if endsWith(base, '_temp')
        rootName = extractBefore(base, strlength(base)-4); % remove _temp
        finalPath = fullfile(allFiles(i).folder, [char(rootName) '.mat']);

        % If corresponding final file exists, process final file only.
        if isfile(finalPath)
            continue;
        end

        % No final file: temp file itself may be a complete dataset.
        candidatePath = fullPath;
        candidateName = base;
    else
        candidatePath = fullPath;
        candidateName = base;
    end

    % Check that annotation exists and has at least one populated frame.
    try
        info = whos('-file', candidatePath);
        vars = {info.name};

        if ~ismember('annotation', vars)
            fprintf('SKIP %-35s : no annotation variable\n', fname);
            continue;
        end

        Tann = load(candidatePath, 'annotation');
        ann = Tann.annotation;

        hasData = false;
        for f = 1:numel(ann)
            if (isfield(ann(f),'contour1') && ~isempty(ann(f).contour1)) || ...
               (isfield(ann(f),'contour2') && ~isempty(ann(f).contour2))
                hasData = true;
                break;
            end
        end

        if ~hasData
            fprintf('SKIP %-35s : annotation exists but is empty\n', fname);
            continue;
        end

        datasetPaths{end+1,1} = candidatePath; %#ok<SAGROW>
        datasetNames{end+1,1} = candidateName; %#ok<SAGROW>

    catch ME
        fprintf('SKIP %-35s : %s\n', fname, ME.message);
    end
end

nDatasets = numel(datasetPaths);

if nDatasets == 0
    error('No usable annotated MAT datasets found.');
end

fprintf('\nUsable datasets found: %d\n\n', nDatasets);

%% ================= MASTER SUMMARY =================
masterDataset       = strings(nDatasets,1);
masterFrames        = nan(nDatasets,1);
masterValid         = nan(nDatasets,1);
masterFailed        = nan(nDatasets,1);
masterMinArea       = nan(nDatasets,1);
masterMinFrame      = nan(nDatasets,1);
masterMaxArea       = nan(nDatasets,1);
masterMaxFrame      = nan(nDatasets,1);
masterMeanArea      = nan(nDatasets,1);
masterMedianArea    = nan(nDatasets,1);

%% ================= PROCESS EACH DATASET =================
for d = 1:nDatasets

    matFilePath = datasetPaths{d};
    datasetName = datasetNames{d};

    fprintf('\n\n############################################################\n');
    fprintf('DATASET %d / %d : %s\n', d, nDatasets, datasetName);
    fprintf('############################################################\n');

    Sann = load(matFilePath, 'annotation');
    nFrames = numel(Sann.annotation);

    areaPixels = nan(nFrames,1);
    success = false(nFrames,1);
    failureMessage = strings(nFrames,1);

    UL_all    = nan(nFrames,2);
    LL_all    = nan(nFrames,2);
    VEL_all   = nan(nFrames,2);
    C2end_all = nan(nFrames,2);

    datasetOut = fullfile(outputRoot, datasetName);
    if ~exist(datasetOut, 'dir')
        mkdir(datasetOut);
    end

    failureOut = fullfile(datasetOut, 'failed_frames');
    if saveFailureFigures && ~exist(failureOut, 'dir')
        mkdir(failureOut);
    end

    for frameIdx = 1:nFrames

        fprintf('\n========== %s | FRAME %d / %d ==========\n', ...
            datasetName, frameIdx, nFrames);

        try
            %% -------- LOAD --------
            data = loadData(matFilePath, frameIdx);

            if isempty(data.C1) || isempty(data.C2)
                error('Frame %d has missing C1/C2 contour.', frameIdx);
            end

            if isempty(data.L) || any(~isfinite(data.L))
                error('Frame %d has missing/invalid L.', frameIdx);
            end

            if isempty(data.VEL_manual) || any(~isfinite(data.VEL_manual))
                error('Frame %d has missing/invalid manual VEL.', frameIdx);
            end

            %% -------- PREPROCESS --------
            C1 = preprocessData(data.C1);
            C2 = preprocessData(data.C2);

            C1 = identifyC1(C1);
            C2 = identifyC2(C2);

            L = data.L;
            VEL_manual = data.VEL_manual;

            %% -------- AXIS --------
            axisVec = VEL_manual - L;

            if norm(axisVec) < eps
                error('Frame %d has degenerate L->VEL axis.', frameIdx);
            end

            axisA = axisVec / norm(axisVec);

            %% -------- START POINTS --------
            [UL, idxUL, ~] = findC1Start(C1, L, axisA);

            % Updated robust version: UL is supplied to findC2Start.
            [LL, idxLL, ~] = findC2Start(C2, L, axisA, UL);

            %% -------- END POINTS --------
            % Preserve your current existing function signatures.
            [VEL, velIdx] = findC1End(C1, VEL_manual, tolerancePx);
            [C2end, idxC2end] = findC2End(C2, VEL, axisA, tolerancePx);

            %% -------- NORMALIZE INDICES --------
            idxULscalar    = normalizeContourIndex(idxUL);
            idxLLscalar    = normalizeContourIndex(idxLL);
            velIdxScalar   = normalizeContourIndex(velIdx);
            idxC2endScalar = normalizeContourIndex(idxC2end);

            %% -------- ORAL AREA POLYGON --------
            upperArc = getContourArcBatch(C1, idxULscalar, ...
                                          velIdxScalar, UL, VEL);

            lowerArc = getContourArcBatch(C2, idxLLscalar, ...
                                          idxC2endScalar, LL, C2end);

            areaPoly = [upperArc; flipud(lowerArc)];

            if size(areaPoly,1) < 3 || any(~isfinite(areaPoly(:)))
                error('Frame %d produced an invalid oral-area polygon.', frameIdx);
            end

            areaValue = polyarea(areaPoly(:,1), areaPoly(:,2));

            if ~isfinite(areaValue) || areaValue <= 0
                error('Frame %d produced invalid oral area.', frameIdx);
            end

            areaPixels(frameIdx) = areaValue;
            success(frameIdx) = true;

            UL_all(frameIdx,:)    = UL;
            LL_all(frameIdx,:)    = LL;
            VEL_all(frameIdx,:)   = VEL;
            C2end_all(frameIdx,:) = C2end;

            fprintf('ORAL AREA = %.6f pixel^2\n', areaValue);

            %% -------- OPTIONAL FRAME DISPLAY --------
            if showFrameFigures
                fig = figure(100);
                clf(fig);

                if ~isempty(data.image)
                    imagesc(data.image);
                    colormap gray;
                    axis image;
                    set(gca,'YDir','reverse');
                    hold on;
                else
                    hold on;
                    axis equal;
                    set(gca,'YDir','reverse');
                end

                patch(areaPoly(:,1), areaPoly(:,2), [1 1 1], ...
                    'FaceAlpha',1.0, ...
                    'EdgeColor','none');

                plot(C1(:,1), C1(:,2), 'r-', 'LineWidth',1.5);
                plot(C2(:,1), C2(:,2), 'g-', 'LineWidth',1.5);

                plot(UL(1), UL(2), 'o', 'MarkerSize',7, ...
                    'MarkerFaceColor','y');
                plot(LL(1), LL(2), 'o', 'MarkerSize',7, ...
                    'MarkerFaceColor','c');
                plot(VEL(1), VEL(2), 'o', 'MarkerSize',7, ...
                    'MarkerFaceColor','m');
                plot(C2end(1), C2end(2), 'o', 'MarkerSize',7, ...
                    'MarkerFaceColor','b');

                title(sprintf('%s | Frame %d/%d | Area %.3f pixel^2', ...
                    datasetName, frameIdx, nFrames, areaValue), ...
                    'Interpreter','none');

                drawnow;
            end

        catch ME
            success(frameIdx) = false;
            failureMessage(frameIdx) = string(ME.message);

            fprintf(2, 'FAILED: %s\n', ME.message);

            if saveFailureFigures
                fFail = figure('Visible','off');
                axis off;
                text(0.05,0.5,sprintf('%s\nFrame %d\n%s', ...
                    datasetName, frameIdx, ME.message), ...
                    'Interpreter','none');

                exportgraphics(fFail, ...
                    fullfile(failureOut, sprintf('frame_%03d_FAILED.png',frameIdx)), ...
                    'Resolution',150);
                close(fFail);
            end
        end
    end

    %% ================= SAVE PER-FRAME TABLE =================
    Frame = (1:nFrames)';
    Area_pixel2 = areaPixels;
    Valid = success;
    Failure = failureMessage;

    resultsTable = table(Frame, Area_pixel2, Valid, ...
        UL_all(:,1), UL_all(:,2), ...
        LL_all(:,1), LL_all(:,2), ...
        VEL_all(:,1), VEL_all(:,2), ...
        C2end_all(:,1), C2end_all(:,2), Failure, ...
        'VariableNames', { ...
        'Frame','Area_pixel2','Valid', ...
        'UL_X','UL_Y','LL_X','LL_Y', ...
        'VEL_X','VEL_Y','C2end_X','C2end_Y','FailureMessage'});

    csvPath = fullfile(datasetOut, [datasetName '_oral_area.csv']);
    writetable(resultsTable, csvPath);

    matOutPath = fullfile(datasetOut, [datasetName '_oral_area_results.mat']);
    save(matOutPath, ...
        'areaPixels','success','failureMessage', ...
        'UL_all','LL_all','VEL_all','C2end_all', ...
        'matFilePath','datasetName');

    %% ================= SAVE AREA GRAPH =================
    validIdx = find(success & isfinite(areaPixels));

    if ~isempty(validIdx)
        figArea = figure('Visible','off', 'Color','w');
        plot(validIdx, areaPixels(validIdx), '-o', ...
            'LineWidth',1.5, 'MarkerSize',3);

        grid on;
        xlabel('Frame');
        ylabel('Oral Area (pixel^2)');
        title(sprintf('%s - Oral Area vs Frame', datasetName), ...
            'Interpreter','none');

        xlim([1 nFrames]);

        pngPath = fullfile(datasetOut, ...
            [datasetName '_oral_area_vs_frame.png']);
        figPath = fullfile(datasetOut, ...
            [datasetName '_oral_area_vs_frame.fig']);

        exportgraphics(figArea, pngPath, 'Resolution',300);
        savefig(figArea, figPath);
        close(figArea);

        %% -------- DATASET STATISTICS --------
        validAreas = areaPixels(validIdx);

        [minA, pMin] = min(validAreas);
        [maxA, pMax] = max(validAreas);

        minFrame = validIdx(pMin);
        maxFrame = validIdx(pMax);

        meanA = mean(validAreas);
        medianA = median(validAreas);

        summaryTable = table( ...
            string(datasetName), nFrames, numel(validIdx), ...
            nFrames-numel(validIdx), ...
            minA, minFrame, maxA, maxFrame, meanA, medianA, ...
            'VariableNames', { ...
            'Dataset','TotalFrames','ValidFrames','FailedFrames', ...
            'MinArea_pixel2','MinAreaFrame', ...
            'MaxArea_pixel2','MaxAreaFrame', ...
            'MeanArea_pixel2','MedianArea_pixel2'});

        writetable(summaryTable, ...
            fullfile(datasetOut, [datasetName '_summary.csv']));

        masterDataset(d)    = string(datasetName);
        masterFrames(d)     = nFrames;
        masterValid(d)      = numel(validIdx);
        masterFailed(d)     = nFrames-numel(validIdx);
        masterMinArea(d)    = minA;
        masterMinFrame(d)   = minFrame;
        masterMaxArea(d)    = maxA;
        masterMaxFrame(d)   = maxFrame;
        masterMeanArea(d)   = meanA;
        masterMedianArea(d) = medianA;

        fprintf('\nSAVED FOR %s:\n', datasetName);
        fprintf('  CSV   : %s\n', csvPath);
        fprintf('  MAT   : %s\n', matOutPath);
        fprintf('  PNG   : %s\n', pngPath);
        fprintf('  FIG   : %s\n', figPath);
        fprintf('  Valid : %d / %d frames\n', numel(validIdx), nFrames);
        fprintf('  Min   : %.4f pixel^2 at frame %d\n', minA, minFrame);
        fprintf('  Max   : %.4f pixel^2 at frame %d\n', maxA, maxFrame);

    else
        masterDataset(d) = string(datasetName);
        masterFrames(d) = nFrames;
        masterValid(d) = 0;
        masterFailed(d) = nFrames;

        fprintf(2, '\nNo valid oral-area frames for %s.\n', datasetName);
    end
end

%% ================= MASTER SUMMARY CSV =================
masterSummary = table( ...
    masterDataset, masterFrames, masterValid, masterFailed, ...
    masterMinArea, masterMinFrame, ...
    masterMaxArea, masterMaxFrame, ...
    masterMeanArea, masterMedianArea, ...
    'VariableNames', { ...
    'Dataset','TotalFrames','ValidFrames','FailedFrames', ...
    'MinArea_pixel2','MinAreaFrame', ...
    'MaxArea_pixel2','MaxAreaFrame', ...
    'MeanArea_pixel2','MedianArea_pixel2'});

masterPath = fullfile(outputRoot, 'MASTER_oral_area_summary.csv');
writetable(masterSummary, masterPath);

fprintf('\n\n============================================================\n');
fprintf('BATCH PROCESSING COMPLETE\n');
fprintf('Master summary:\n%s\n', masterPath);
fprintf('============================================================\n');

%% ================================================================
% LOCAL HELPERS
% ================================================================

function idx = normalizeContourIndex(idxIn)
% Convert scalar / [i i] / [i i+1] index output into one valid scalar.
    if isempty(idxIn)
        error('Empty contour index.');
    end

    idxIn = idxIn(:);
    idx = round(idxIn(1));

    if ~isfinite(idx) || idx < 1
        error('Invalid contour index.');
    end
end

function segment = getContourArcBatch(C, idxStart, idxEnd, Pstart, Pend)
% Extract ordered contour samples between two scalar indices and force the
% exact interpolated endpoints into the polygon.

    n = size(C,1);

    idxStart = max(1, min(n, round(idxStart)));
    idxEnd   = max(1, min(n, round(idxEnd)));

    lo = min(idxStart, idxEnd);
    hi = max(idxStart, idxEnd);

    segment = C(lo:hi,:);

    % Orient segment from start endpoint toward end endpoint.
    dNormal = norm(segment(1,:) - Pstart) + norm(segment(end,:) - Pend);
    dFlip   = norm(segment(end,:) - Pstart) + norm(segment(1,:) - Pend);

    if dFlip < dNormal
        segment = flipud(segment);
    end

    % Exact interpolated/anatomical endpoints.
    segment = [Pstart; segment; Pend];

    % Remove consecutive duplicates.
    if size(segment,1) > 1
        keep = [true; any(abs(diff(segment,1,1)) > 1e-12, 2)];
        segment = segment(keep,:);
    end
end
