function visualizeFinalResult(MRI, ...
    C1, C2, C3, ...
    UL, LL, VEL, C2end)
% VISUALIZEFINALRESULT
%
% Final anatomical result over the ORIGINAL MRI FRAME.
%
% No circle markers.
% No contour point markers.
%
% Four selected anatomical points:
%   UL     = C1 start
%   LL     = C2 start
%   VEL    = C1 end
%   C2end  = C2 end

    figure( ...
        'Name', 'FINAL RESULT - MRI FRAME WITH ANATOMICAL POINTS', ...
        'NumberTitle', 'off', ...
        'Color', 'w');

    % ------------------------------------------------------------
    % ORIGINAL MRI FRAME
    % ------------------------------------------------------------

    imagesc(MRI);

    colormap gray;

    axis image;

    hold on;

    % ------------------------------------------------------------
    % C1
    % ------------------------------------------------------------

    plot(C1(:,1), C1(:,2), ...
        'r-', ...
        'LineWidth', 1.7, ...
        'DisplayName', 'C1');

    % ------------------------------------------------------------
    % C2
    % ------------------------------------------------------------

    plot(C2(:,1), C2(:,2), ...
        'g-', ...
        'LineWidth', 1.7, ...
        'DisplayName', 'C2');

    % ------------------------------------------------------------
    % C3
    % ------------------------------------------------------------

    if ~isempty(C3)

        plot(C3(:,1), C3(:,2), ...
            'c-', ...
            'LineWidth', 1.7, ...
            'DisplayName', 'C3');

    end

    % ------------------------------------------------------------
    % UL
    % ------------------------------------------------------------

    plot(UL(1), UL(2), ...
        'y*', ...
        'MarkerSize', 13, ...
        'LineWidth', 2, ...
        'DisplayName', 'UL');

    text( ...
        UL(1)+2, ...
        UL(2), ...
        'UL', ...
        'Color', 'y', ...
        'FontWeight', 'bold', ...
        'FontSize', 10);

    % ------------------------------------------------------------
    % LL
    % ------------------------------------------------------------

    plot(LL(1), LL(2), ...
        'y+', ...
        'MarkerSize', 13, ...
        'LineWidth', 2, ...
        'DisplayName', 'LL');

    text( ...
        LL(1)+2, ...
        LL(2), ...
        'LL', ...
        'Color', 'y', ...
        'FontWeight', 'bold', ...
        'FontSize', 10);

    % ------------------------------------------------------------
    % VEL
    % ------------------------------------------------------------

    plot(VEL(1), VEL(2), ...
        'b*', ...
        'MarkerSize', 14, ...
        'LineWidth', 2, ...
        'DisplayName', 'VEL');

    text( ...
        VEL(1)+2, ...
        VEL(2), ...
        'VEL', ...
        'Color', 'b', ...
        'FontWeight', 'bold', ...
        'FontSize', 10);

    % ------------------------------------------------------------
    % C2 END
    % ------------------------------------------------------------

    plot(C2end(1), C2end(2), ...
        'm*', ...
        'MarkerSize', 14, ...
        'LineWidth', 2, ...
        'DisplayName', 'C2 END');

    text( ...
        C2end(1)+2, ...
        C2end(2), ...
        'C2 END', ...
        'Color', 'm', ...
        'FontWeight', 'bold', ...
        'FontSize', 10);

    % ------------------------------------------------------------
    % DISPLAY
    % ------------------------------------------------------------

    title('Final Anatomical Points on Original MRI Frame');

    xlabel('X');
    ylabel('Y');

    legend( ...
        'show', ...
        'Location', 'bestoutside');

    set(gca, 'YDir', 'reverse');

    hold off;

end