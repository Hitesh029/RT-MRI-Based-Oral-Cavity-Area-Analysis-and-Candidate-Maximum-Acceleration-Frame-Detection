%% batch_oral_area_all_files.m
% Batch-process many MRI annotation MAT files automatically.
%
% Put this file + process_oral_area_file.m in your MATLAB project folder.
% Keep your existing detection helper files in the same MATLAB path.
%
% The script:
%   1) Finds MAT datasets in inputFolder.
%   2) Groups X.mat and X_temp.mat as the same dataset.
%   3) Prefers the file with the more complete annotation.
%   4) Runs the established oral-area calculation.
%   5) Saves per-dataset CSV + MAT + PNG + FIG.
%   6) Saves one master summary CSV/MAT across all datasets.
%
% It does NOT calculate velocity or acceleration yet.

clear; clc; close all;

%% CONFIGURATION
inputFolder = pwd;
outputRoot = fullfile(pwd, 'oral_area_results_all_files');

% 0 = fastest batch processing; no artificial display delay.
% This is NOT MRI dt / temporal resolution.
frameDelay = 0;

if ~exist(outputRoot,'dir')
    mkdir(outputRoot);
end

%% FIND INPUT MAT FILES
D = dir(fullfile(inputFolder,'*.mat'));

% Ignore files generated by this pipeline.
ignoreTokens = ["summary","detection_summary","results"];
keep = true(size(D));
for i = 1:numel(D)
    lname = lower(string(D(i).name));
    for t = ignoreTokens
        if contains(lname,t)
            keep(i) = false;
        end
    end
end
D = D(keep);

if isempty(D)
    error('No input MAT files found in: %s', inputFolder);
end

%% GROUP final MAT and *_temp.mat versions
% Example:
%   M1_400.mat
%   M1_400_temp.mat
% are treated as one dataset named M1_400.

groupKeys = strings(numel(D),1);
for i = 1:numel(D)
    [~,nm,~] = fileparts(D(i).name);
    nm = string(nm);
    if endsWith(nm,"_temp")
        nm = extractBefore(nm,strlength(nm)-4); % remove "_temp"
    end
    groupKeys(i) = nm;
end

uniqueGroups = unique(groupKeys,'stable');

dataset = strings(0,1);
inputFile = strings(0,1);
totalFrames = zeros(0,1);
validAreaFrames = zeros(0,1);
failedFrames = zeros(0,1);
minArea = nan(0,1);
maxArea = nan(0,1);
maxAreaFrame = nan(0,1);
runStatus = strings(0,1);
errorMessage = strings(0,1);

fprintf('\n========================================\n');
fprintf('BATCH ORAL-AREA PROCESSING\n');
fprintf('Datasets found: %d\n',numel(uniqueGroups));
fprintf('Output root: %s\n',outputRoot);
fprintf('========================================\n');

for g = 1:numel(uniqueGroups)

    key = uniqueGroups(g);
    candidateIdx = find(groupKeys == key);

    % Choose the candidate with the strongest populated annotation.
    bestScore = -Inf;
    bestPath = "";

    for j = candidateIdx(:).'
        p = fullfile(D(j).folder,D(j).name);
        score = annotationScore(p);

        fprintf('Candidate %-35s annotation score = %.0f\n', ...
            D(j).name,score);

        if score > bestScore
            bestScore = score;
            bestPath = string(p);
        end
    end

    dataset(end+1,1) = key;
    inputFile(end+1,1) = bestPath;

    fprintf('\n----------------------------------------\n');
    fprintf('Dataset %d/%d: %s\n',g,numel(uniqueGroups),key);
    fprintf('Selected input: %s\n',bestPath);
    fprintf('----------------------------------------\n');

    try
        s = process_oral_area_file(char(bestPath),outputRoot,frameDelay);

        totalFrames(end+1,1) = s.nFrames;
        validAreaFrames(end+1,1) = s.validAreaFrames;
        failedFrames(end+1,1) = s.failedFrames;

        A = s.areaPixels;
        valid = isfinite(A);

        if any(valid)
            minArea(end+1,1) = min(A(valid));
            [mx,idx] = max(A);
            maxArea(end+1,1) = mx;
            maxAreaFrame(end+1,1) = idx;
        else
            minArea(end+1,1) = NaN;
            maxArea(end+1,1) = NaN;
            maxAreaFrame(end+1,1) = NaN;
        end

        runStatus(end+1,1) = "COMPLETED";
        errorMessage(end+1,1) = "";

    catch ME
        totalFrames(end+1,1) = NaN;
        validAreaFrames(end+1,1) = 0;
        failedFrames(end+1,1) = NaN;
        minArea(end+1,1) = NaN;
        maxArea(end+1,1) = NaN;
        maxAreaFrame(end+1,1) = NaN;
        runStatus(end+1,1) = "FAILED";
        errorMessage(end+1,1) = string(ME.message);

        fprintf(2,'Dataset %s FAILED: %s\n',key,ME.message);
    end
end

%% MASTER SUMMARY
masterSummary = table(dataset,inputFile,totalFrames,validAreaFrames, ...
    failedFrames,minArea,maxArea,maxAreaFrame,runStatus,errorMessage);

masterCsv = fullfile(outputRoot,'MASTER_oral_area_summary.csv');
masterMat = fullfile(outputRoot,'MASTER_oral_area_summary.mat');

writetable(masterSummary,masterCsv);
save(masterMat,'masterSummary');

fprintf('\n========================================\n');
fprintf('BATCH COMPLETE\n');
fprintf('Completed datasets: %d\n',sum(runStatus=="COMPLETED"));
fprintf('Failed datasets: %d\n',sum(runStatus=="FAILED"));
fprintf('Master CSV: %s\n',masterCsv);
fprintf('Master MAT: %s\n',masterMat);
fprintf('========================================\n');

disp(masterSummary);


%% ================================================================
% LOCAL HELPER: estimate how much annotation is populated
% ================================================================
function score = annotationScore(matPath)

    score = -1;

    try
        S = load(matPath,'annotation');

        if ~isfield(S,'annotation') || isempty(S.annotation)
            return;
        end

        ann = S.annotation;
        score = 0;

        % Check every frame because some files may have only partial work.
        fields = {'contour1','contour2','contour3','UL','LL','VEL'};

        for k = 1:numel(ann)
            for f = 1:numel(fields)
                name = fields{f};

                if isfield(ann(k),name)
                    v = ann(k).(name);

                    if ~isempty(v)
                        % One point for a landmark; number of rows for contours.
                        if isnumeric(v)
                            score = score + max(1,size(v,1));
                        else
                            score = score + 1;
                        end
                    end
                end
            end
        end

    catch
        score = -1;
    end
end
