function visualizeC2(MRI, C2, L, axisA, ...
    LL, idxLL, VEL, tangentVec, ...
    C2end, idxC2end)
% VISUALIZEC2
% C2 start/end detection over original MRI frame.
%
% No circle markers.
% No square bracket markers.

    figure( ...
        'Name', 'C2 - LL and C2 END Detection', ...
        'NumberTitle', 'off', ...
        'Color', 'w');

    imagesc(MRI);
    colormap gray;
    axis image;
    hold on;

    % ------------------------------------------------------------
    % C2
    % ------------------------------------------------------------

    plot(C2(:,1), C2(:,2), ...
        'g-', ...
        'LineWidth', 1.5, ...
        'DisplayName', 'C2');

    % ------------------------------------------------------------
    % L
    % ------------------------------------------------------------

    plot(L(1), L(2), ...
        'wx', ...
        'MarkerSize', 10, ...
        'LineWidth', 2, ...
        'DisplayName', 'L');

    % ------------------------------------------------------------
    % LL
    % ------------------------------------------------------------

    plot(LL(1), LL(2), ...
        'y*', ...
        'MarkerSize', 12, ...
        'LineWidth', 2, ...
        'DisplayName', 'LL');

    text(LL(1)+2, LL(2), ...
        'LL', ...
        'Color', 'y', ...
        'FontWeight', 'bold');

    % ------------------------------------------------------------
    % VEL
    % ------------------------------------------------------------

    plot(VEL(1), VEL(2), ...
        'b*', ...
        'MarkerSize', 12, ...
        'LineWidth', 2, ...
        'DisplayName', 'VEL');

    text(VEL(1)+2, VEL(2), ...
        'VEL', ...
        'Color', 'b', ...
        'FontWeight', 'bold');

    % ------------------------------------------------------------
    % TANGENT
    % ------------------------------------------------------------

    scale = 15;

    quiver( ...
        VEL(1), VEL(2), ...
        tangentVec(1)*scale, ...
        tangentVec(2)*scale, ...
        0, ...
        'k', ...
        'LineWidth', 2, ...
        'MaxHeadSize', 2, ...
        'DisplayName', 'C1 tangent');

    % ------------------------------------------------------------
    % NORMAL / C2 END CUTTING LINE
    % ------------------------------------------------------------

    normalVec = [-tangentVec(2), tangentVec(1)];

    Lscale = 50;

    P1 = VEL - Lscale*normalVec;
    P2 = VEL + Lscale*normalVec;

    plot([P1(1) P2(1)], ...
         [P1(2) P2(2)], ...
         'm--', ...
         'LineWidth', 1.3, ...
         'DisplayName', 'C2-end cutting line');

    % ------------------------------------------------------------
    % C2 END
    % ------------------------------------------------------------

    plot(C2end(1), C2end(2), ...
        'm*', ...
        'MarkerSize', 13, ...
        'LineWidth', 2, ...
        'DisplayName', 'C2 END');

    text(C2end(1)+2, C2end(2), ...
        'C2 END', ...
        'Color', 'm', ...
        'FontWeight', 'bold');

    title(sprintf( ...
        'C2 Detection - C2 END = (%.2f, %.2f)', ...
        C2end(1), C2end(2)));

    xlabel('X');
    ylabel('Y');

    legend('show', 'Location', 'best');

    set(gca, 'YDir', 'reverse');

    hold off;

end