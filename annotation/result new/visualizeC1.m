function visualizeC1(MRI, C1, L, axisA, ...
    UL, idxUL, VEL, velIdx)
% VISUALIZEC1
% C1 start/end detection over original MRI frame.
%
% No circle markers.

    figure( ...
        'Name', 'C1 - UL and VEL Detection', ...
        'NumberTitle', 'off', ...
        'Color', 'w');

    imagesc(MRI);
    colormap gray;
    axis image;
    hold on;

    % C1 contour
    plot(C1(:,1), C1(:,2), ...
        'r-', ...
        'LineWidth', 1.5, ...
        'DisplayName', 'C1');

    % L
    plot(L(1), L(2), ...
        'wx', ...
        'MarkerSize', 10, ...
        'LineWidth', 2, ...
        'DisplayName', 'L');

    % UL
    plot(UL(1), UL(2), ...
        'y*', ...
        'MarkerSize', 12, ...
        'LineWidth', 2, ...
        'DisplayName', 'UL');

    text(UL(1)+2, UL(2), ...
        'UL', ...
        'Color', 'y', ...
        'FontWeight', 'bold');

    % VEL
    plot(VEL(1), VEL(2), ...
        'b*', ...
        'MarkerSize', 12, ...
        'LineWidth', 2, ...
        'DisplayName', 'VEL');

    text(VEL(1)+2, VEL(2), ...
        'VEL', ...
        'Color', 'b', ...
        'FontWeight', 'bold');

    % ------------------------------------------------------------
    % ANTERIOR REFERENCE LINE
    % ------------------------------------------------------------

    n = [-axisA(2), axisA(1)];

    scale = 30;

    P1 = L - scale*n;
    P2 = L + scale*n;

    plot([P1(1) P2(1)], ...
         [P1(2) P2(2)], ...
         'y--', ...
         'LineWidth', 1.2, ...
         'DisplayName', 'Anterior reference line');

    title(sprintf( ...
        'C1 Detection - UL = (%.2f, %.2f)', ...
        UL(1), UL(2)));

    xlabel('X');
    ylabel('Y');

    legend('show', 'Location', 'best');

    set(gca, 'YDir', 'reverse');

    hold off;

end